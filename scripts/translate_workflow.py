for loc, tx in translations.items():
    path = os.path.join(root, f'{loc}.json')
    with open(path, 'r', encoding='utf-8-sig') as f:
        data = json.load(f)
    lw = data.get('levelingWorkflow', {})
    updated = 0
    for k, v in tx.items():
        if k in lw and lw[k] != v:
            lw[k] = v
            updated += 1
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\ufeff' + json.dumps(data, indent=4, ensure_ascii=False))
    print(f'{loc}: {updated} keys updated')
